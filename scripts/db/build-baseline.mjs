#!/usr/bin/env node
// Writes supabase/baseline/schema.sql: the live database's schema (everything the app owns),
// in an order a fresh Supabase database can apply. See supabase/baseline/README.md.
//
// Refresh from the live database (needs a Supabase personal access token; read-only):
//   SUPABASE_ACCESS_TOKEN=... node scripts/db/build-baseline.mjs
// Or from rows already fetched with scripts/db/baseline-objects.sql (JSON array, or a saved
// Supabase MCP result), naming the last migration version they include:
//   node scripts/db/build-baseline.mjs --from rows.json --version 20261105054849

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const args = process.argv.slice(2);
const arg = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};
const projectRef = arg('--project') ?? process.env.SUPABASE_PROJECT_REF ?? 'lxoeotyibsalbxgbjfxo';
const outFile = arg('--out') ?? join(root, 'supabase', 'baseline', 'schema.sql');

// Accepts a plain JSON array, or the text the Supabase MCP returns (the array sits inside an
// untrusted-data wrapper, JSON-escaped).
function parseRows(text) {
  let t = text.trim();
  if (t.startsWith('{"result"')) t = JSON.parse(t).result;
  const start = t.indexOf('[{');
  const end = t.lastIndexOf('}]');
  if (start < 0 || end < 0) throw new Error('No JSON rows found in input');
  return JSON.parse(t.slice(start, end + 2));
}

async function query(sql) {
  const token = process.env.SUPABASE_ACCESS_TOKEN;
  if (!token) throw new Error('Set SUPABASE_ACCESS_TOKEN, or pass --from <file> --version <version>');
  const res = await fetch(`https://api.supabase.com/v1/projects/${projectRef}/database/query`, {
    method: 'POST',
    headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ query: sql, read_only: true }),
  });
  if (!res.ok) throw new Error(`Management API ${res.status}: ${await res.text()}`);
  return res.json();
}

let rows;
let version = arg('--version');
if (arg('--from')) {
  rows = parseRows(readFileSync(arg('--from'), 'utf8'));
  if (!version) throw new Error('--from needs --version (the newest migration the rows include)');
} else {
  rows = await query(readFileSync(join(root, 'scripts', 'db', 'baseline-objects.sql'), 'utf8'));
  const [{ version: v }] = await query('select max(version) as version from supabase_migrations.schema_migrations');
  version = v;
}

const byKind = (kind) => rows.filter((r) => r.kind === kind).sort((a, b) => a.name.localeCompare(b.name));

// Functions and views can depend on each other (a view calls a function; a function returns a
// view's row type). Order them so every dependency comes first; ties by kind, then name.
function topoSort(items) {
  const byOid = new Map(items.map((r) => [String(r.oid), r]));
  const pending = new Map(items.map((r) => [String(r.oid), new Set((r.deps ?? []).map(String).filter((d) => byOid.has(d) && d !== String(r.oid)))]));
  const out = [];
  const rank = (r) => `${r.kind === 'function' ? 0 : 1}:${r.name}`;
  while (pending.size) {
    const ready = [...pending].filter(([, deps]) => deps.size === 0).map(([oid]) => byOid.get(oid));
    if (!ready.length) throw new Error(`Dependency cycle among: ${[...pending.keys()].map((o) => byOid.get(o).name).join(', ')}`);
    ready.sort((a, b) => rank(a).localeCompare(rank(b)));
    const next = ready[0];
    out.push(next);
    pending.delete(String(next.oid));
    for (const deps of pending.values()) deps.delete(String(next.oid));
  }
  return out;
}

const section = (title, items) =>
  items.length ? `\n-- ${'='.repeat(94)}\n-- ${title} (${items.length})\n-- ${'='.repeat(94)}\n\n${items.map((r) => r.ddl.trim()).join('\n\n')}\n` : '';

const known = new Set(['extension', 'table', 'function', 'view', 'default', 'key', 'check', 'fkey', 'index',
  'replica_identity', 'trigger', 'rls', 'policy', 'grant', 'comment', 'publication', 'bucket']);
const unknown = rows.filter((r) => !known.has(r.kind));
if (unknown.length) throw new Error(`Unhandled object kinds: ${[...new Set(unknown.map((r) => r.kind))].join(', ')}`);

const header = `-- Shorty Harris database baseline: the live schema as of migration ${version}.
-- Generated by scripts/db/build-baseline.mjs from scripts/db/baseline-objects.sql. Do not edit by
-- hand; regenerate it. See supabase/baseline/README.md for what it contains and how it is used.
--
-- Applies to a fresh Supabase database (auth, storage and realtime already set up by Supabase).
-- Migrations newer than ${version} in supabase/migrations are applied on top of it.
-- NOT for the live project: everything here already exists there.

begin;
set local check_function_bodies = false;
set local client_min_messages = warning;
set local search_path = '';
`;

const sql = [
  header,
  section('Extensions', byKind('extension')),
  section('Tables (columns only; defaults and other constraints follow)', byKind('table')),
  // Before views: a view may GROUP BY a primary key and select the other columns.
  section('Primary keys and unique constraints', byKind('key')),
  section('Functions and views (dependency order)', topoSort([...byKind('function'), ...byKind('view')])),
  section('Column defaults', byKind('default')),
  section('Check constraints', byKind('check')),
  section('Foreign keys', byKind('fkey')),
  section('Indexes', byKind('index')),
  section('Replica identity (realtime)', byKind('replica_identity')),
  section('Triggers (including on auth.users)', byKind('trigger')),
  section('Row level security', byKind('rls')),
  section('Policies (public and storage)', byKind('policy')),
  section('Privileges (exactly as live; Supabase default privileges are reset first)', byKind('grant')),
  section('Comments', byKind('comment')),
  section('Realtime publication', byKind('publication')),
  section('Storage buckets', byKind('bucket')),
  `\nset local search_path = public, extensions;\ncommit;\n`,
].join('');

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, sql);
const counts = Object.fromEntries([...known].map((k) => [k, rows.filter((r) => r.kind === k).length]));
console.log(`Wrote ${outFile} (${(sql.length / 1024).toFixed(0)} KB) as of ${version}`);
console.log(counts);
